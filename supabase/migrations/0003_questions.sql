-- Helper: insert one MCQ + its options by (track, unit position, level position).
-- Options are a JSON array of {"b": body, "c": is_correct}; positions/labels
-- are assigned in array order.
create or replace function seed_q(
  p_track       exam_track,
  p_unit_pos    int,
  p_level_pos   int,
  p_difficulty  int,
  p_body        text,
  p_explanation text,
  p_opts        jsonb
) returns void
language plpgsql
as $$
declare
  v_level_id bigint;
  v_qid      bigint;
  v_pos      int := 0;
  v_opt      jsonb;
begin
  select l.id into v_level_id
  from levels l
  join units u on u.id = l.unit_id
  where u.track = p_track and u.position = p_unit_pos and l.position = p_level_pos;

  if v_level_id is null then
    raise exception 'level not found: track=% unit=% level=%', p_track, p_unit_pos, p_level_pos;
  end if;

  insert into questions (track, level_id, difficulty, body, explanation, source, is_active)
  values (p_track, v_level_id, p_difficulty, p_body, p_explanation, 'original', true)
  returning id into v_qid;

  for v_opt in select * from jsonb_array_elements(p_opts) loop
    insert into answer_options (question_id, label, body, is_correct, position)
    values (v_qid, (v_pos + 1)::text, v_opt->>'b', coalesce((v_opt->>'c')::boolean, false), v_pos);
    v_pos := v_pos + 1;
  end loop;
end;
$$;

